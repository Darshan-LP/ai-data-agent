
"""FastAPI application for the AI Data Agent."""

from pathlib import Path
from time import perf_counter
from typing import Any

from fastapi import FastAPI, HTTPException
from fastapi.responses import FileResponse
from pydantic import BaseModel, Field
from sqlalchemy import text

from app.agent.loop import run_agent
from app.config import get_settings
from app.db import admin_engine, readonly_engine
from app.observability.runs import log_run, recent_runs


app = FastAPI(
    title="AI Data Agent",
    version="0.4.0",
    description=(
        "An AI-powered analytics agent that answers questions "
        "about business data using safe SQL, charts, and Excel reports."
    ),
)


# ---------------------------------------------------------
# Request and response models
# ---------------------------------------------------------

class AgentRequest(BaseModel):
    question: str = Field(
        ...,
        min_length=1,
        max_length=2000,
        description="A natural-language question about the business data.",
    )


class ArtifactLink(BaseModel):
    name: str
    url: str
    kind: str


class AgentResponse(BaseModel):
    success: bool
    answer: str
    error: str | None = None
    artifacts: list[ArtifactLink] = Field(default_factory=list)

    # Observability information
    trace: list[dict[str, Any]] = Field(default_factory=list)
    sql_generated: list[str] = Field(default_factory=list)
    input_tokens: int | None = None
    output_tokens: int | None = None
    cost_usd: float | None = None
    latency_ms: int | None = None


# ---------------------------------------------------------
# Helpers
# ---------------------------------------------------------

def _database_is_available(engine_factory: Any) -> bool:
    """Check whether a database connection can execute a simple query."""

    try:
        engine = engine_factory()
        with engine.connect() as connection:
            connection.execute(text("SELECT 1"))
        return True
    except Exception:
        return False


def _get_trace(result: Any) -> list[dict[str, Any]]:
    """Convert agent steps into API-friendly dictionaries."""

    return [
        {
            "step_number": step.step_number,
            "action": step.action,
            "details": step.details,
        }
        for step in result.steps
    ]


def _get_generated_sql(result: Any) -> list[str]:
    """Extract SQL statements recorded in agent tool calls."""

    statements = []

    for step in result.steps:
        if step.action != "tool_call":
            continue

        if step.details.get("tool") != "run_sql_query":
            continue

        arguments = step.details.get("arguments")

        if not isinstance(arguments, dict):
            continue

        sql = arguments.get("sql")

        if isinstance(sql, str):
            statements.append(sql)

    return statements


def _get_artifact_links(result: Any) -> list[ArtifactLink]:
    """Create download links for files generated by the agent."""

    settings = get_settings()
    links = []

    # Generated files are stored in the project's artifacts directory.
    artifacts_directory = Path(settings.outputs_dir).resolve()

    for artifact in result.artifacts:
        filename = artifact.get("filename", "")

        # Only allow a filename, not an arbitrary filesystem path.
        if (
            not filename
            or Path(filename).name != filename
            or "\\" in filename
            or "/" in filename
        ):
            continue

        file_path = (artifacts_directory / filename).resolve()

        # Ensure the file remains inside the artifacts directory.
        if file_path.parent != artifacts_directory:
            continue

        if file_path.suffix.lower() not in {".png", ".html", ".xlsx"}:
            continue

        if not file_path.is_file():
            continue

        links.append(
            ArtifactLink(
                name=filename,
                url=f"/artifacts/{filename}",
                kind=artifact.get("label", "Generated file"),
            )
        )

    return links


# ---------------------------------------------------------
# Health endpoint
# ---------------------------------------------------------

@app.get("/health")
def health() -> dict[str, Any]:
    """Report API and database connectivity."""

    settings = get_settings()

    admin_ok = _database_is_available(admin_engine)
    readonly_ok = _database_is_available(readonly_engine)

    healthy = admin_ok and readonly_ok

    return {
        "status": "ok" if healthy else "degraded",
        "postgres_host": getattr(settings, "postgres_host", None),
        "postgres_db": getattr(settings, "postgres_db", None),
        "admin_connection": admin_ok,
        "readonly_connection": readonly_ok,
    }


# ---------------------------------------------------------
# Artifact download endpoint
# ---------------------------------------------------------

@app.get("/artifacts/{filename}")
def download_artifact(filename: str) -> FileResponse:
    """Serve generated chart and Excel files."""

    if (
        not filename
        or Path(filename).name != filename
        or "/" in filename
        or "\\" in filename
    ):
        raise HTTPException(
            status_code=400,
            detail="Invalid artifact filename.",
        )

    allowed_types = {
        ".png": "image/png",
        ".html": "text/html",
        ".xlsx": (
            "application/vnd.openxmlformats-officedocument."
            "spreadsheetml.sheet"
        ),
    }

    suffix = Path(filename).suffix.lower()

    if suffix not in allowed_types:
        raise HTTPException(
            status_code=400,
            detail="Unsupported artifact type.",
        )

    settings = get_settings()
    artifacts_directory = Path(settings.outputs_dir).resolve()
    file_path = (artifacts_directory / filename).resolve()

    if file_path.parent != artifacts_directory or not file_path.is_file():
        raise HTTPException(
            status_code=404,
            detail="Artifact not found.",
        )

    return FileResponse(
        path=file_path,
        media_type=allowed_types[suffix],
        filename=filename,
    )


# ---------------------------------------------------------
# Run agent endpoint
# ---------------------------------------------------------

@app.post("/agent/run", response_model=AgentResponse)
def run_agent_endpoint(request: AgentRequest) -> AgentResponse:
    """Run the agent, record its usage, and return its result."""

    question = request.question.strip()

    if not question:
        raise HTTPException(
            status_code=422,
            detail="Question cannot be empty.",
        )

    started_at = perf_counter()

    result = run_agent(question)

    latency_ms = max(
        0,
        int((perf_counter() - started_at) * 1000),
    )

    # Save the run even when the agent reports a failure.
    try:
        log_run(
            question=question,
            run=result,
            latency_ms=latency_ms,
        )
    except Exception:
        # A logging failure should not hide the agent's actual result.
        import logging
        logging.getLogger(__name__).exception(
            "Failed to save agent run history."
        )

    # Preserve the existing API behaviour for unsuccessful agent runs.
    if not result.success:
        raise HTTPException(
            status_code=502,
            detail={
                "message": result.answer,
                "error": result.error,
            },
        )

    artifact_links = _get_artifact_links(result)

    return AgentResponse(
        success=result.success,
        answer=result.answer,
        error=result.error,
        artifacts=artifact_links,
        trace=_get_trace(result),
        sql_generated=_get_generated_sql(result),
        input_tokens=result.input_tokens,
        output_tokens=result.output_tokens,
        cost_usd=result.cost_usd,
        latency_ms=latency_ms,
    )


# ---------------------------------------------------------
# Run history endpoint
# ---------------------------------------------------------

@app.get("/runs")
def get_runs(limit: int = 20) -> dict[str, Any]:
    """Return recent agent runs from PostgreSQL."""

    if limit < 1 or limit > 100:
        raise HTTPException(
            status_code=422,
            detail="Limit must be between 1 and 100.",
        )

    return {
        "runs": recent_runs(limit),
    }
